package io.pinforge.model

import org.json.JSONArray
import org.json.JSONObject
import java.io.File

data class Placed(val id: String, val type: String, val x: Float, val y: Float)

/** One connection from a part pin to a board header pin (key like "L3" / "R12"). */
data class Wire(val part: String, val pin: String, val board: String)

data class Wiring(val parts: List<Placed> = emptyList(), val wires: List<Wire> = emptyList()) {
    fun toJson(): String = JSONObject().apply {
        put("parts", JSONArray().apply {
            parts.forEach { put(JSONObject().put("id", it.id).put("type", it.type).put("x", it.x.toDouble()).put("y", it.y.toDouble())) }
        })
        put("wires", JSONArray().apply {
            wires.forEach { put(JSONObject().put("part", it.part).put("pin", it.pin).put("board", it.board)) }
        })
    }.toString(2)

    companion object {
        fun parse(s: String): Wiring = try {
            val o = JSONObject(s)
            val pa = o.optJSONArray("parts") ?: JSONArray()
            val wa = o.optJSONArray("wires") ?: JSONArray()
            Wiring(
                (0 until pa.length()).map { i ->
                    val p = pa.getJSONObject(i)
                    Placed(p.getString("id"), p.getString("type"), p.optDouble("x").toFloat(), p.optDouble("y").toFloat())
                },
                (0 until wa.length()).map { i ->
                    val w = wa.getJSONObject(i)
                    Wire(w.getString("part"), w.getString("pin"), w.getString("board"))
                }
            )
        } catch (_: Exception) {
            Wiring()
        }
    }
}

data class Project(
    val name: String,
    val dir: File,
    val boardId: String,
    val method: String = "usb",      // "usb" | "ota"
    val otaHost: String = "",
) {
    val sketch get() = File(dir, "$name.ino")
    val buildDir get() = File(dir, "build")
}

class ProjectStore(private val root: File) {
    init { root.mkdirs() }

    fun list(): List<String> =
        root.listFiles()?.filter { File(it, "${it.name}.ino").exists() }?.map { it.name }?.sorted() ?: emptyList()

    fun sanitize(name: String): String {
        val s = name.trim().replace(Regex("[^A-Za-z0-9_]"), "_")
        return if (s.isEmpty() || !s[0].isLetter()) "Sketch_$s" else s
    }

    fun create(rawName: String, boardId: String): Project {
        val name = sanitize(rawName)
        val dir = File(root, name)
        require(!dir.exists()) { "A project named $name already exists" }
        dir.mkdirs()
        val p = Project(name, dir, boardId)
        p.sketch.writeText(
            """
            #include "wiring.h"

            void setup() {
              Serial.begin(115200);
            }

            void loop() {
            }
            """.trimIndent() + "\n"
        )
        File(dir, "wiring.h").writeText("#pragma once\n// Generated by PinForge — use the Wiring tab.\n")
        saveMeta(p)
        return p
    }

    fun load(name: String): Project {
        val dir = File(root, name)
        val meta = File(dir, "project.json").takeIf { it.exists() }?.readText()?.let { JSONObject(it) } ?: JSONObject()
        return Project(
            name, dir,
            meta.optString("board", "uno"),
            meta.optString("method", "usb"),
            meta.optString("otaHost", ""),
        )
    }

    fun saveMeta(p: Project) {
        File(p.dir, "project.json").writeText(
            JSONObject().put("board", p.boardId).put("method", p.method).put("otaHost", p.otaHost).toString(2)
        )
    }

    fun delete(name: String) = File(root, name).deleteRecursively()

    fun readWiring(p: Project): Wiring =
        File(p.dir, "wiring.json").takeIf { it.exists() }?.readText()?.let { Wiring.parse(it) } ?: Wiring()

    fun writeWiring(p: Project, w: Wiring) = File(p.dir, "wiring.json").writeText(w.toJson())
}
