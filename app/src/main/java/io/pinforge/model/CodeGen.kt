package io.pinforge.model

/** Turns a wiring diagram into wiring.h, a starter sketch, a library list, and sanity checks. */
object CodeGen {

    private fun fill(t: String, id: String) = t.replace("{id}", id).replace("{ID}", id.uppercase())

    private fun types(w: Wiring) = w.parts.mapNotNull { pl -> Parts.byId(pl.type)?.let { pl to it } }

    private fun wireFor(w: Wiring, part: String, pin: String) = w.wires.firstOrNull { it.part == part && it.pin == pin }

    fun header(board: Board, w: Wiring): String {
        val sb = StringBuilder()
        sb.append("// Generated by PinForge for ${board.name} (${board.fqbn}).\n")
        sb.append("// Edit the wiring in the app and regenerate; manual edits here are overwritten.\n")
        sb.append("#pragma once\n\n")
        var sda: String? = null; var scl: String? = null
        var mosi: String? = null; var miso: String? = null; var sck: String? = null
        for ((pl, t) in types(w)) {
            val lines = mutableListOf<String>()
            for (cp in t.pins) {
                val bp = wireFor(w, pl.id, cp.name)?.let { board.pin(it.board) } ?: continue
                val code = bp.code ?: continue
                when (cp.role) {
                    Role.SDA -> if (sda == null) sda = code
                    Role.SCL -> if (scl == null) scl = code
                    Role.MOSI -> if (mosi == null) mosi = code
                    Role.MISO -> if (miso == null) miso = code
                    Role.SCK -> if (sck == null) sck = code
                    else -> {}
                }
                lines += "#define ${pl.id.uppercase()}_${cp.name.uppercase()} $code   // ${bp.label}"
            }
            if (lines.isNotEmpty()) {
                sb.append("// ${pl.id}: ${t.name}\n")
                lines.forEach { sb.append(it).append('\n') }
                sb.append('\n')
            }
        }
        if (sda != null && scl != null) {
            sb.append("#define I2C_SDA $sda\n#define I2C_SCL $scl\n")
            sb.append(
                """
                #if defined(ARDUINO_ARCH_ESP32)
                  #define PF_WIRE_BEGIN() Wire.begin(I2C_SDA, I2C_SCL)
                #elif defined(ARDUINO_ARCH_RP2040)
                  #define PF_WIRE_BEGIN() do { Wire.setSDA(I2C_SDA); Wire.setSCL(I2C_SCL); Wire.begin(); } while (0)
                #else
                  #define PF_WIRE_BEGIN() Wire.begin()
                #endif
                """.trimIndent() + "\n\n"
            )
        } else {
            sb.append("#define PF_WIRE_BEGIN() Wire.begin()\n")
        }
        if (mosi != null && miso != null && sck != null) {
            sb.append("#define SPI_MOSI_PIN $mosi\n#define SPI_MISO_PIN $miso\n#define SPI_SCK_PIN $sck\n")
            sb.append(
                """
                #if defined(ARDUINO_ARCH_ESP32)
                  #define PF_SPI_BEGIN() SPI.begin(SPI_SCK_PIN, SPI_MISO_PIN, SPI_MOSI_PIN)
                #elif defined(ARDUINO_ARCH_RP2040)
                  #define PF_SPI_BEGIN() do { SPI.setRX(SPI_MISO_PIN); SPI.setTX(SPI_MOSI_PIN); SPI.setSCK(SPI_SCK_PIN); SPI.begin(); } while (0)
                #else
                  #define PF_SPI_BEGIN() SPI.begin()
                #endif
                """.trimIndent() + "\n"
            )
        } else {
            sb.append("#define PF_SPI_BEGIN() SPI.begin()\n")
        }
        return sb.toString()
    }

    fun libraries(board: Board, w: Wiring): List<String> =
        types(w).flatMap { (_, t) -> t.libs(board.arch) }.distinct()

    fun starter(board: Board, w: Wiring): String {
        val ts = types(w)
        val inc = LinkedHashSet<String>()
        if (ts.any { it.second.usesI2c }) inc += "Wire.h"
        if (ts.any { it.second.usesSpi }) inc += "SPI.h"
        ts.forEach { (_, t) -> inc += t.includes(board.arch) }

        fun block(sel: (PartType) -> String, indent: String) = ts.filter { sel(it.second).isNotBlank() }
            .joinToString("\n") { (pl, t) ->
                "$indent// ${pl.id}\n" + fill(sel(t), pl.id).lines().joinToString("\n") { indent + it }
            }

        val sb = StringBuilder()
        sb.append("// Starter sketch generated by PinForge for ${board.name}.\n")
        sb.append("#include <Arduino.h>\n")
        inc.forEach { sb.append("#include <$it>\n") }
        sb.append("#include \"wiring.h\"\n\n")
        val g = block({ it.globals }, "")
        if (g.isNotBlank()) sb.append(g).append("\n\n")
        sb.append("void setup() {\n  Serial.begin(115200);\n  delay(200);\n")
        if (ts.any { it.second.usesI2c }) sb.append("  PF_WIRE_BEGIN();\n")
        if (ts.any { it.second.usesSpi }) sb.append("  PF_SPI_BEGIN();\n")
        val s = block({ it.setup }, "  ")
        if (s.isNotBlank()) sb.append(s).append('\n')
        sb.append("}\n\nvoid loop() {\n")
        val l = block({ it.loop }, "  ")
        if (l.isNotBlank()) sb.append(l).append("\n\n")
        val per = block({ it.periodic }, "    ")
        if (per.isNotBlank()) {
            sb.append("  static uint32_t pfLast = 0;\n  if (millis() - pfLast >= 1000) {\n    pfLast = millis();\n")
            sb.append(per).append("\n  }\n")
        }
        sb.append("}\n")
        return sb.toString()
    }

    /** Human-readable problems with the current wiring. */
    fun check(board: Board, w: Wiring): List<String> {
        val out = mutableListOf<String>()
        val signalUse = mutableMapOf<String, MutableList<String>>()
        val fixedBus = board.arch != Arch.ESP32 && board.arch != Arch.RP2040
        for ((pl, t) in types(w)) {
            if (t.archOnly != null && board.arch !in t.archOnly) out += "${pl.id}: ${t.name} isn't supported on ${board.name}"
            for (cp in t.pins) {
                val wire = wireFor(w, pl.id, cp.name)
                if (wire == null) { out += "${pl.id}.${cp.name} is not connected"; continue }
                val bp = board.pin(wire.board) ?: continue
                val where = "${pl.id}.${cp.name} → ${bp.label}"
                when (cp.role) {
                    Role.VCC -> {
                        if (!bp.isPower) out += "$where: VCC should go to a power pin"
                        else if (t.wants5v && !bp.has("PWR5")) out += "$where: ${t.name} usually needs 5V"
                    }
                    Role.GND -> if (!bp.isGnd) out += "$where: should go to GND"
                    Role.ANALOG -> if (!bp.has("A")) out += "$where: not an analog-capable pin"
                    Role.SDA, Role.SCL, Role.MOSI, Role.MISO, Role.SCK -> {
                        if (bp.code == null) out += "$where: not a GPIO"
                        else if (fixedBus && !bp.has(cp.role.name)) out += "$where: ${board.name} uses fixed ${cp.role} pins"
                    }
                    Role.SIG, Role.CS -> {
                        if (bp.code == null) out += "$where: not a GPIO"
                        else if (bp.has("IN") && !cp.input) out += "$where: input-only pin, can't drive outputs"
                    }
                }
                if (bp.has("X")) out += "$where: boot/USB/serial pin — may misbehave"
                if (cp.role == Role.SIG || cp.role == Role.ANALOG || cp.role == Role.CS) {
                    signalUse.getOrPut(wire.board) { mutableListOf() } += "${pl.id}.${cp.name}"
                }
            }
        }
        signalUse.filter { it.value.size > 1 }.forEach { (k, v) ->
            out += "${board.pin(k)?.label} is shared by ${v.joinToString(", ")}"
        }
        if (board.volts == "3.3V" && types(w).any { it.second.id == "hcsr04" }) {
            out += "HC-SR04 ECHO outputs 5V — add a resistor divider on this 3.3V board"
        }
        return out
    }

    /** Fills every unconnected part pin with a sensible board pin. */
    fun autoWire(board: Board, w: Wiring): Wiring {
        val wires = w.wires.toMutableList()
        val keyed = board.keyed()
        val taken = wires.mapNotNull { wr -> board.pin(wr.board)?.let { p -> if (!p.isPower && !p.isGnd) wr.board else null } }.toMutableSet()
        val busPin = mutableMapOf<Role, String>()
        wires.forEach { wr ->
            val cp = Parts.byId(w.parts.firstOrNull { it.id == wr.part }?.type ?: "")?.pins?.firstOrNull { it.name == wr.pin }
            if (cp != null && cp.role in setOf(Role.SDA, Role.SCL, Role.MOSI, Role.MISO, Role.SCK)) busPin[cp.role] = wr.board
        }
        fun free(pred: (Pin) -> Boolean): String? =
            keyed.firstOrNull { (k, p) -> k !in taken && p.code != null && !p.has("X") && pred(p) }?.first
                ?: keyed.firstOrNull { (k, p) -> k !in taken && p.code != null && pred(p) }?.first

        for ((pl, t) in types(w)) {
            for (cp in t.pins) {
                if (wires.any { it.part == pl.id && it.pin == cp.name }) continue
                val key: String? = when (cp.role) {
                    Role.GND -> keyed.firstOrNull { it.second.isGnd }?.first
                    Role.VCC -> {
                        val five = keyed.firstOrNull { it.second.has("PWR5") }?.first
                        val three = keyed.firstOrNull { it.second.has("PWR3") }?.first
                        if (t.wants5v || board.volts == "5V") five ?: three else three ?: five
                    }
                    Role.SDA, Role.SCL, Role.MOSI, Role.MISO, Role.SCK ->
                        busPin[cp.role] ?: free { it.has(cp.role.name) }?.also { busPin[cp.role] = it; taken += it }
                    Role.ANALOG -> free { it.has("A") }?.also { taken += it }
                    Role.SIG, Role.CS -> free { it.has("D") && (cp.input || !it.has("IN")) }?.also { taken += it }
                }
                if (key != null) wires += Wire(pl.id, cp.name, key)
            }
        }
        return w.copy(wires = wires)
    }
}
